import type { Analysis, Finding, Footprint, Severity, Workflow } from '../types'
import { buildJobGraph, JOB_NODE_HEIGHT, JOB_NODE_WIDTH } from './layout'

const SEVERITY_ORDER: Severity[] = ['critical', 'warning', 'info']
const SEVERITY_LABEL: Record<Severity, string> = {
  critical: 'Critical',
  warning: 'Warning',
  info: 'Info',
}
const SEVERITY_COLOR: Record<Severity, string> = {
  critical: '#ff6b6b',
  warning: '#ffb454',
  info: '#7dd3fc',
}

const PADDING = 42
const HEADER_HEIGHT = 92

function escapeXml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;')
}

function escapeMarkdown(value: string): string {
  return value.replaceAll('|', '\\|').replace(/\n/g, ' ')
}

function escapeMermaid(value: string): string {
  return value.replaceAll('"', '#quot;').replaceAll('\n', ' ')
}

function truncate(value: string, length: number): string {
  return value.length > length ? `${value.slice(0, length - 1)}…` : value
}

function workflowName(workflow: Workflow): string {
  if (workflow.name) return workflow.name
  if (!workflow.sourceName) return 'workflow'
  const base = workflow.sourceName.split(/[\\/]/).pop() ?? workflow.sourceName
  return base.replace(/\.ya?ml$/i, '') || 'workflow'
}

function jobCounts(findings: Finding[], jobId: string): Record<Severity, number> {
  const counts: Record<Severity, number> = { critical: 0, warning: 0, info: 0 }
  for (const finding of findings) {
    if (finding.job === jobId) counts[finding.severity] += 1
  }
  return counts
}

function permissionsLabel(workflow: Workflow): string {
  if (!workflow.permissions) return 'inherited (not declared)'
  if (workflow.permissions.all) return workflow.permissions.all
  const scopes = Object.entries(workflow.permissions.scopes)
  if (scopes.length === 0) return 'none'
  return scopes.map(([scope, access]) => `${scope}: ${access}`).join(', ')
}

function matrixLabel(workflow: Workflow, jobId: string): string {
  const job = workflow.jobs.find((candidate) => candidate.id === jobId)
  if (!job?.matrix) return '—'
  if (job.matrix.dynamic || job.matrix.count === null) return 'dynamic'
  return `×${job.matrix.count}`
}

export function toMermaid(workflow: Workflow, findings: Finding[]): string {
  const ids = new Map<string, string>()
  workflow.jobs.forEach((job, index) => ids.set(job.id, `j_${index}`))

  const lines = ['flowchart LR', '  %% Generated by ActionLens']
  lines.push(
    '  classDef critical fill:#2a1417,stroke:#ff6b6b,color:#f5f7fa;',
    '  classDef warning fill:#2a1e10,stroke:#ffb454,color:#f5f7fa;',
    '  classDef info fill:#0e2230,stroke:#7dd3fc,color:#f5f7fa;',
    '  classDef clean fill:#101a26,stroke:#5aa9ff,color:#f5f7fa;',
  )

  for (const job of workflow.jobs) {
    const id = ids.get(job.id) ?? 'j_unknown'
    const subtitle = job.uses ? 'reusable workflow' : job.runsOn.join(' · ') || 'no runner'
    const label = `${escapeMermaid(job.name ?? job.id)}<br/><small>${escapeMermaid(truncate(subtitle, 36))}</small>`
    const counts = jobCounts(findings, job.id)
    const tone: Severity | 'clean' =
      counts.critical > 0
        ? 'critical'
        : counts.warning > 0
          ? 'warning'
          : counts.info > 0
            ? 'info'
            : 'clean'
    lines.push(`  ${id}["${label}"]:::${tone}`)
  }

  for (const job of workflow.jobs) {
    for (const dependency of job.needs) {
      const source = ids.get(job.id)
      const target = ids.get(dependency)
      if (!source || !target) continue
      lines.push(`  ${source} -->|needs| ${target}`)
    }
  }

  return `${lines.join('\n')}\n`
}

export function toMarkdown(
  workflow: Workflow,
  analysis: Analysis,
  footprint: Footprint,
): string {
  const triggers = workflow.triggers.events.join(', ') || 'none'
  const lines = [
    `# ActionLens report — ${escapeMarkdown(workflowName(workflow))}`,
    '',
    '> Generated locally with [ActionLens](https://github.com/hix-pro/action-lens). No file was uploaded.',
    '',
    '## Summary',
    '',
    '| Jobs | Job instances | Steps | Actions | Critical | Warnings | Info |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    `| ${analysis.stats.jobs} | ${analysis.stats.instances}${analysis.stats.dynamicMatrices > 0 ? '+' : ''} | ${analysis.stats.steps} | ${analysis.stats.actions} | ${analysis.counts.critical} | ${analysis.counts.warning} | ${analysis.counts.info} |`,
    '',
    `**Triggers:** ${escapeMarkdown(triggers)}`,
    '',
    `**Token permissions:** ${escapeMarkdown(permissionsLabel(workflow))}`,
    '',
    '## Run footprint',
    '',
    `- **Job instances:** ${footprint.instances}${footprint.dynamic ? '+' : ''} per run`,
    `- **Assumption:** ${footprint.minutesPerJob} minutes per job`,
    `- **Estimated runner time:** ${footprint.minutes} minutes per run`,
    `- **Estimated private-repo cost:** $${footprint.costUsd.toFixed(2)} per run at $${footprint.pricePerMinute.toFixed(3)}/min`,
    '',
    '> Planning estimate only. Step duration varies, matrix expressions can change the job count, and public repositories are free.',
    '',
    '## Jobs',
    '',
    '| Job | Runner or reusable workflow | Matrix | Needs | Steps | Timeout |',
    '| --- | --- | --- | --- | --- | --- |',
  ]

  for (const job of workflow.jobs) {
    const runner = job.uses ?? job.runsOn.join(', ') ?? '—'
    const needs = job.needs.join(', ') || '—'
    const timeout = job.timeoutMinutes ? `${job.timeoutMinutes} min` : '—'
    lines.push(
      `| \`${escapeMarkdown(job.id)}\` | ${escapeMarkdown(runner || '—')} | ${matrixLabel(workflow, job.id)} | ${escapeMarkdown(needs)} | ${job.steps.length} | ${timeout} |`,
    )
  }

  lines.push('', '## Findings', '')

  if (analysis.findings.length === 0) {
    lines.push('No findings from the current rule set. This is not a security audit.')
  }

  for (const severity of SEVERITY_ORDER) {
    const group = analysis.findings.filter((finding) => finding.severity === severity)
    if (group.length === 0) continue
    lines.push(`### ${SEVERITY_LABEL[severity]} (${group.length})`, '')
    for (const finding of group) {
      const scope = finding.job ? ` — \`${finding.job}\`` : ''
      lines.push(`- **${escapeMarkdown(finding.title)}**${scope}`)
      lines.push(`  - ${escapeMarkdown(finding.detail)}`)
      lines.push(`  - **Fix:** ${escapeMarkdown(finding.fix)}`)
    }
    lines.push('')
  }

  return `${lines.join('\n').trim()}\n`
}

export function toJsonReport(
  workflow: Workflow,
  analysis: Analysis,
  footprint: Footprint,
): string {
  return `${JSON.stringify(
    {
      tool: 'action-lens',
      version: 1,
      name: workflowName(workflow),
      source: workflow.sourceName ?? null,
      triggers: workflow.triggers,
      permissions: workflow.permissions ?? null,
      concurrency: workflow.concurrency ?? null,
      summary: analysis.stats,
      counts: analysis.counts,
      footprint,
      jobs: workflow.jobs.map((job) => ({
        id: job.id,
        name: job.name ?? null,
        needs: job.needs,
        runsOn: job.runsOn,
        uses: job.uses ?? null,
        matrix: job.matrix
          ? {
              count: job.matrix.count,
              dynamic: job.matrix.dynamic,
              dimensions: Object.fromEntries(
                Object.entries(job.matrix.dimensions).map(([key, values]) => [
                  key,
                  values.length,
                ]),
              ),
            }
          : null,
        timeoutMinutes: job.timeoutMinutes ?? null,
        permissions: job.permissions ?? null,
        secretsInherit: job.secretsInherit,
        steps: job.steps.map((step) => ({
          name: step.name ?? null,
          uses: step.uses ?? null,
          hasRun: Boolean(step.run),
          withKeys: Object.keys(step.with),
          envKeys: Object.keys(step.env),
        })),
      })),
      findings: analysis.findings.map((finding) => ({
        rule: finding.rule,
        severity: finding.severity,
        job: finding.job ?? null,
        step: finding.step ?? null,
        title: finding.title,
        detail: finding.detail,
        fix: finding.fix,
      })),
    },
    null,
    2,
  )}\n`
}

export function toSvg(workflow: Workflow, findings: Finding[]): string {
  const graph = buildJobGraph(workflow, findings)

  if (graph.nodes.length === 0) {
    return '<svg xmlns="http://www.w3.org/2000/svg" width="480" height="160"><rect width="480" height="160" fill="#070a0f"/><text x="24" y="88" fill="#8b98a9" font-family="Inter, sans-serif" font-size="14">No jobs to render.</text></svg>'
  }

  const xs = graph.nodes.map((node) => node.position.x)
  const ys = graph.nodes.map((node) => node.position.y)
  const minX = Math.min(...xs)
  const minY = Math.min(...ys)
  const maxX = Math.max(...xs) + JOB_NODE_WIDTH
  const maxY = Math.max(...ys) + JOB_NODE_HEIGHT
  const width = Math.ceil(maxX - minX + PADDING * 2)
  const height = Math.ceil(maxY - minY + PADDING * 2 + HEADER_HEIGHT)
  const offsetX = PADDING - minX
  const offsetY = PADDING + HEADER_HEIGHT - minY
  const positions = new Map(
    graph.nodes.map((node) => [
      node.id,
      { x: node.position.x + offsetX, y: node.position.y + offsetY },
    ]),
  )

  const counts = {
    critical: findings.filter((finding) => finding.severity === 'critical').length,
    warning: findings.filter((finding) => finding.severity === 'warning').length,
    info: findings.filter((finding) => finding.severity === 'info').length,
  }
  const instances = workflow.jobs.reduce(
    (total, job) => total + (job.matrix?.count ?? 1),
    0,
  )

  const parts: string[] = []
  parts.push(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" font-family="Inter, ui-sans-serif, system-ui, sans-serif">`,
    '<defs>',
    '<pattern id="dots" width="24" height="24" patternUnits="userSpaceOnUse"><circle cx="1" cy="1" r="1" fill="#1b2633" opacity="0.65"/></pattern>',
    '<marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" fill="#46545f"/></marker>',
    '</defs>',
    `<rect width="${width}" height="${height}" fill="#070a0f"/>`,
    `<rect width="${width}" height="${height}" fill="url(#dots)"/>`,
    `<text x="${PADDING}" y="38" fill="#f5f7fa" font-size="20" font-weight="700">${escapeXml(workflowName(workflow))}</text>`,
    `<text x="${PADDING}" y="64" fill="#8b98a9" font-size="12">${workflow.jobs.length} jobs · ${instances} job instances · ${counts.critical} critical · ${counts.warning} warnings · generated by ActionLens</text>`,
    `<line x1="${PADDING}" y1="${HEADER_HEIGHT - 16}" x2="${width - PADDING}" y2="${HEADER_HEIGHT - 16}" stroke="#1b2633" />`,
  )

  for (const edge of graph.edges) {
    const source = positions.get(edge.source)
    const target = positions.get(edge.target)
    if (!source || !target) continue
    const x1 = source.x + JOB_NODE_WIDTH
    const y1 = source.y + JOB_NODE_HEIGHT / 2
    const x2 = target.x
    const y2 = target.y + JOB_NODE_HEIGHT / 2
    const curve = Math.max(46, Math.abs(x2 - x1) * 0.45)
    parts.push(
      `<path d="M ${x1} ${y1} C ${x1 + curve} ${y1}, ${x2 - curve} ${y2}, ${x2} ${y2}" fill="none" stroke="#354657" stroke-width="1.6" marker-end="url(#arrow)"/>`,
    )
  }

  for (const node of graph.nodes) {
    const position = positions.get(node.id)
    if (!position) continue
    const { job } = node.data
    const nodeCounts = jobCounts(findings, job.id)
    const accent =
      nodeCounts.critical > 0
        ? SEVERITY_COLOR.critical
        : nodeCounts.warning > 0
          ? SEVERITY_COLOR.warning
          : nodeCounts.info > 0
            ? SEVERITY_COLOR.info
            : '#2b3f55'
    const subtitle = job.uses
      ? truncate(job.uses, 40)
      : job.runsOn.join(' · ') || 'no runner'
    const matrix = job.matrix?.dynamic || job.matrix?.count === null
      ? 'matrix: dynamic'
      : job.matrix
        ? `matrix ×${job.matrix.count}`
        : 'no matrix'
    const findingsLabel =
      nodeCounts.critical + nodeCounts.warning + nodeCounts.info > 0
        ? `${nodeCounts.critical} critical / ${nodeCounts.warning} warning / ${nodeCounts.info} info`
        : 'no findings'

    parts.push(
      `<g transform="translate(${position.x}, ${position.y})">`,
      `<rect width="${JOB_NODE_WIDTH}" height="${JOB_NODE_HEIGHT}" rx="14" fill="#0b1118" stroke="${accent}" stroke-opacity="${accent === '#2b3f55' ? 1 : 0.6}" stroke-width="1.5"/>`,
      `<rect width="${JOB_NODE_WIDTH}" height="3" rx="1.5" fill="${accent}" opacity="${accent === '#2b3f55' ? 0.7 : 1}"/>`,
      `<circle cx="22" cy="31" r="5" fill="${accent}"/>`,
      `<text x="36" y="36" fill="#f5f7fa" font-size="15" font-weight="650">${escapeXml(truncate(job.name ?? job.id, 25))}</text>`,
      `<text x="22" y="58" fill="#8b98a9" font-size="10.5" font-family="JetBrains Mono, ui-monospace, monospace">${escapeXml(job.name ? job.id : subtitle)}</text>`,
      `<line x1="20" y1="71" x2="${JOB_NODE_WIDTH - 20}" y2="71" stroke="#192430"/>`,
      `<text x="22" y="92" fill="#6f7f92" font-size="9.5" letter-spacing="0.08em">${escapeXml(matrix.toUpperCase())}   ${job.steps.length} STEPS   ${job.needs.length} NEEDS</text>`,
      `<text x="22" y="112" fill="#6f7f92" font-size="9.5">${escapeXml(truncate(subtitle, 42))}</text>`,
      `<text x="22" y="134" fill="#7f8c9d" font-size="9.5">${job.timeoutMinutes ? `⏱ timeout ${job.timeoutMinutes} min` : '○ no timeout'}   ·   ${escapeXml(findingsLabel)}</text>`,
      '</g>',
    )
  }

  parts.push('</svg>')
  return parts.join('\n')
}

export function reportFilename(workflow: Workflow, extension: string): string {
  const slug = workflowName(workflow)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
  return `${slug || 'workflow'}-report.${extension}`
}

export function downloadText(filename: string, content: string, type: string): void {
  const blob = new Blob([content], { type })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = filename
  document.body.append(anchor)
  anchor.click()
  anchor.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

export async function downloadSvgAsPng(
  filename: string,
  svg: string,
  scale = 2,
): Promise<void> {
  const blob = new Blob([svg], { type: 'image/svg+xml;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  try {
    const image = new Image()
    image.decoding = 'sync'
    await new Promise<void>((resolve, reject) => {
      image.onload = () => resolve()
      image.onerror = () => reject(new Error('Could not render the SVG export.'))
      image.src = url
    })
    const width = image.naturalWidth || 1200
    const height = image.naturalHeight || 800
    const canvas = document.createElement('canvas')
    canvas.width = Math.ceil(width * scale)
    canvas.height = Math.ceil(height * scale)
    const context = canvas.getContext('2d')
    if (!context) throw new Error('Canvas is not available in this browser.')
    context.scale(scale, scale)
    context.drawImage(image, 0, 0)
    const pngBlob = await new Promise<Blob | null>((resolve) =>
      canvas.toBlob(resolve, 'image/png'),
    )
    if (!pngBlob) throw new Error('Could not encode the PNG.')
    const pngUrl = URL.createObjectURL(pngBlob)
    const anchor = document.createElement('a')
    anchor.href = pngUrl
    anchor.download = filename
    document.body.append(anchor)
    anchor.click()
    anchor.remove()
    setTimeout(() => URL.revokeObjectURL(pngUrl), 1000)
  } finally {
    URL.revokeObjectURL(url)
  }
}
